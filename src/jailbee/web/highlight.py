"""Pygments highlighting with CSS classes styled by the dashboard's design tokens.

Highlighted HTML carries only class names; inherited tokens supply the theme,
including scoped themes and e-ink. Regenerate the committed stylesheet with:

    uv run python -m jailbee.web.highlight > frontend/src/styles/highlight.css
"""

from __future__ import annotations

from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import JsonLexer
from pygments.token import STANDARD_TYPES, Token


def highlight_json(text: str) -> str:
    """``text`` (JSON) as a ``<div class="highlight"><pre>`` block, escaped."""
    formatter = HtmlFormatter(cssclass="highlight", noclasses=False)
    return highlight(text, JsonLexer(), formatter)


def stylesheet() -> str:
    """Use semantic colour roles, not Pygments' independent theme palettes.

    Plain text inherits the code block's surface text colour. The existing
    phase hues distinguish numbers and strings and meet AA on tonal surfaces;
    the e-ink theme resolves every foreground role to black. Error tokens are
    neutralised because an imperfect lexer must not mark valid code as an error.
    """
    rules: list[str] = []
    for token, name in sorted(STANDARD_TYPES.items(), key=lambda item: item[1]):
        if not name:
            continue
        role = None
        ancestors = token.split()
        if Token.Comment in ancestors:
            role = "on-surface-variant"
        elif Token.Keyword in ancestors or Token.Name.Tag in ancestors:
            role = "primary"
        elif Token.Literal.Number in ancestors:
            role = "phase-job"
        elif Token.Literal.String in ancestors:
            role = "phase-autostart"
        if role:
            rules.append(f".highlight .{name} {{ color: var(--md-{role}); }}")
    rules.extend(
        [
            ".highlight .c, .highlight .c1, .highlight .cm { font-style: italic; }",
            ".highlight .nt, .highlight .k, .highlight .kc { font-weight: var(--md-type-emphasis-weight); }",
            '[data-theme="eink"] .highlight .s, [data-theme="eink"] .highlight .s2 { font-style: italic; }',
            ".highlight .ge { font-style: italic; }",
            ".highlight .gs, .highlight .ges { font-weight: var(--md-type-emphasis-weight); }",
            ".highlight .ges { font-style: italic; }",
            ".highlight .gu { text-decoration: underline; }",
            ".highlight .err { color: inherit; background: none; border: none; }",
        ]
    )
    return (
        "/* Generated by `python -m jailbee.web.highlight`; do not edit. */\n"
        + "\n".join(rules)
        + "\n"
    )


if __name__ == "__main__":
    print(stylesheet(), end="")
