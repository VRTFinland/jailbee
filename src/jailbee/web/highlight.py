"""Pygments highlighting with CSS classes, and the stylesheets for those classes.

Ported from codereader. Highlighted HTML carries only class names; colours
come from the stylesheet `stylesheet()` generates, so a theme change is a
CSS swap, never a re-render. The generated file is committed as
``frontend/src/styles/highlight.css``; regenerate it after changing a theme:

    uv run python -m jailbee.web.highlight > frontend/src/styles/highlight.css
"""

from __future__ import annotations

from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import JsonLexer

LIGHT_STYLE = "default"
DARK_STYLE = "github-dark"


def highlight_json(text: str) -> str:
    """``text`` (JSON) as a ``<div class="highlight"><pre>`` block, escaped."""
    formatter = HtmlFormatter(cssclass="highlight", noclasses=False)
    return highlight(text, JsonLexer(), formatter)


def _indent(css: str) -> str:
    return "\n".join(f"    {line}" if line else line for line in css.splitlines())


def _token_rules(style: str) -> str:
    formatter = HtmlFormatter(style=style)
    # The stubs leave this public method unannotated; it returns a list of rules.
    rules: list[str] = formatter.get_token_style_defs(".highlight")  # type: ignore[no-untyped-call]
    return "\n".join(rules)


def stylesheet() -> str:
    """Light colours by default, dark ones under ``prefers-color-scheme: dark``.

    Only token rules are emitted: backgrounds and plain text colour are left
    to the page's own tokens, so a code block sits on the theme's surface.
    Pygments' error token is neutralised: with a wrong lexer it marks valid
    code as an error.
    """
    light = _token_rules(LIGHT_STYLE)
    dark = _token_rules(DARK_STYLE)
    reset = ".highlight .err { color: inherit; background: none; border: none; }"
    return (
        "/* Generated by `python -m jailbee.web.highlight`; do not edit. */\n"
        f"/* Light ({LIGHT_STYLE}) */\n{light}\n\n"
        f"/* Dark ({DARK_STYLE}) */\n@media (prefers-color-scheme: dark) {{\n"
        f"{_indent(dark)}\n}}\n\n{reset}\n"
    )


if __name__ == "__main__":
    print(stylesheet(), end="")
