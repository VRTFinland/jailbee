def test_sync_copies_source_with_marker(homes, claude_cfg):
    source, data_home = homes
    source.write_bytes(b"Never use fable.\n")
    ai.sync_global_instructions(claude_cfg)
    content = staged(data_home).read_bytes()
    first, rest = content.split(b"\n", 1)
    assert first.decode() == (
        f"<!-- generated by jailbee from {source} — edit that file on the host -->"
    )
    assert rest == ai.PREAMBLE.encode() + b"\n\nNever use fable.\n"


def test_preamble_staged_without_source(homes, claude_cfg):
    source, data_home = homes
    ai.sync_global_instructions(claude_cfg)
    marker = f"<!-- generated by jailbee from {source} — edit that file on the host -->"
    assert staged(data_home).read_bytes() == marker.encode() + b"\n" + ai.PREAMBLE.encode() + b"\n"
    for fact in ("jailbee-container", "/etc/jailbee/container.json", "jailbee service"):
        assert fact in ai.PREAMBLE
    assert 15 <= len(ai.PREAMBLE.splitlines()) <= 25
    assert "mode" in ai.PREAMBLE and "repo_dir" in ai.PREAMBLE
    assert "mount mode" in ai.PREAMBLE
    assert "Treat gh as read-only" in ai.PREAMBLE
    assert "jailbee net egress add <host> <container>" in ai.PREAMBLE
    assert "short_name" in ai.PREAMBLE
    assert "JAILBEE_ROLE=child" in ai.PREAMBLE
    assert "jailbee-orchestration-child" in ai.PREAMBLE
    assert "In clone mode, the host operator extracts commits" in ai.PREAMBLE
    assert "mount mode shares the tree" in ai.PREAMBLE
    assert "If you are a child, ask your orchestrator for publication and network access" in ai.PREAMBLE
    assert "Otherwise, ask the operator to publish changes" in ai.PREAMBLE
    assert "jailbee service ls" in ai.PREAMBLE
    assert "jailbee service start <service>" in ai.PREAMBLE
    assert "jailbee service logs <service>" in ai.PREAMBLE


