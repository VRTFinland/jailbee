def test_sync_replaces_staged_file_when_source_deleted(homes, claude_cfg):
    source, data_home = homes
    source.write_bytes(b"x")
    ai.sync_global_instructions(claude_cfg)
    source.unlink()
    ai.sync_global_instructions(claude_cfg)
    assert staged(data_home).read_bytes().endswith(ai.PREAMBLE.encode() + b"\n")
    assert staged(data_home).parent.is_dir()


def test_unchanged_content_is_not_rewritten(homes, claude_cfg):
    source, data_home = homes
    source.write_bytes(b"x")
    ai.sync_global_instructions(claude_cfg)
    before = staged(data_home).stat()
    ai.sync_global_instructions(claude_cfg)
    after = staged(data_home).stat()
    assert (before.st_ino, before.st_mtime_ns) == (after.st_ino, after.st_mtime_ns)


def test_changed_content_is_replaced_atomically(homes, claude_cfg):
    source, data_home = homes
    source.write_bytes(b"old")
    ai.sync_global_instructions(claude_cfg)
    before_ino = staged(data_home).stat().st_ino
    source.write_bytes(b"new")
    ai.sync_global_instructions(claude_cfg)
    assert staged(data_home).read_bytes().endswith(b"\nnew")
    assert staged(data_home).stat().st_ino != before_ino
    assert [p.name for p in staged(data_home).parent.iterdir()] == ["CLAUDE.md"]


