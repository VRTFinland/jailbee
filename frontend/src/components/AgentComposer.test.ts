import {mount} from "@vue/test-utils"
import {beforeEach, describe, expect, it, vi} from "vitest"

beforeEach(() => localStorage.setItem("jailbee.composerExpanded", "1"))
import AgentComposer from "./AgentComposer.vue"

describe("agent composer", () => {
    it("collapses on mobile, persists a choice and preserves the draft", async () => {
        localStorage.removeItem("jailbee.composerExpanded")
        const oldWidth = window.innerWidth
        Object.defineProperty(window, "innerWidth", {configurable: true, value: 390})
        const w = mount(AgentComposer, {attachTo: document.body, props: {available: true, draft: "draft"}})
        expect(w.find("textarea").exists()).toBe(false)
        await w.get('[aria-label="Message agent"]').trigger("click")
        expect(document.activeElement).toBe(w.get("textarea").element)
        await w.get('[aria-label="Hide composer"]').trigger("click")
        expect(w.find("textarea").exists()).toBe(false)
        await w.get('[aria-label="Message agent"]').trigger("click")
        expect((w.get("textarea").element as HTMLTextAreaElement).value).toBe("draft")
        expect(localStorage.getItem("jailbee.composerExpanded")).toBe("1")
        w.unmount()
        Object.defineProperty(window, "innerWidth", {configurable: true, value: oldWidth})
        localStorage.removeItem("jailbee.composerExpanded")
    })
    it("sends on Enter but not Shift+Enter or IME composition", async () => {
        const w = mount(AgentComposer, {props: {available: true, draft: "hello"}})
        const field = w.get("textarea")
        for (const options of [{shiftKey: true}, {isComposing: true}, {keyCode: 229}]) {
            const event = new KeyboardEvent("keydown", {key: "Enter", bubbles: true, cancelable: true, ...options})
            field.element.dispatchEvent(event)
            expect(event.defaultPrevented).toBe(false)
        }
        expect(w.emitted("send")).toBeUndefined()
        await field.trigger("keydown", {key: "Enter"})
        expect(w.emitted("send")?.[0]).toEqual(["hello"])
    })
    it("offers phone users a newline at the cursor without sending", async () => {
        const w = mount(AgentComposer, {attachTo: document.body, props: {available: true, draft: "firstsecond"}})
        const field = w.get('textarea').element as HTMLTextAreaElement
        expect(field.getAttribute('enterkeyhint')).toBe('send')
        field.setSelectionRange(5, 5)
        await w.get('[aria-label="Insert newline"]').trigger('click')
        expect(w.emitted('update:draft')?.[0]).toEqual(['first\nsecond'])
        expect(field.selectionStart).toBe(6)
        expect(document.activeElement).toBe(field)
        expect(w.emitted('send')).toBeUndefined()
        w.unmount()
    })
    it("shows a fresh send result before availability, then restores the reason", async () => {
        vi.useFakeTimers()
        const w = mount(AgentComposer, {props: {available: false, reason: "No live agent"}})
        const row = w.get('[role="status"]')
        expect(row.text()).toBe('No live agent')
        await w.setProps({error: 'The agent is waiting at a dialog in the terminal; answer it there first.'})
        expect(row.text()).toContain('waiting at a dialog')
        await vi.advanceTimersByTimeAsync(5000)
        expect(row.text()).toBe('No live agent')
        await w.setProps({error: '', sending: true})
        expect(row.text()).toBe('Sending…')
        await w.setProps({sending: false, status: 'Delivered'})
        expect(row.text()).toBe('Delivered')
        await vi.advanceTimersByTimeAsync(5000)
        expect(row.text()).toBe('No live agent')
        w.unmount()
        vi.useRealTimers()
    })
    it("reserves one polite status row across changes", async () => {
        const w = mount(AgentComposer, {props: {available: true}})
        const row = w.get('[aria-live="polite"]')
        expect(row.text()).toBe("")
        await w.setProps({status: "Delivered"})
        expect(row.text()).toBe("Delivered")
        await w.setProps({error: "Failed", status: ""})
        expect(row.text()).toBe("Failed")
    })
    it("emits the intact message and exposes sending state", async () => {
        const w = mount(AgentComposer, {props: {available: true}})
        await w.get("textarea").setValue("first\nsecond")
        await w.get('[aria-label="Send message"]').trigger("click")
        expect(w.emitted("send")?.[0]).toEqual(["first\nsecond"])
        await w.setProps({sending: true})
        expect(w.get('[aria-label="Send message"]').attributes("disabled")).toBeDefined()
    })
    it("locks the draft while waiting and exposes it to the parent", async () => {
        const w = mount(AgentComposer, {props: {available: true, draft: "first draft"}})
        await w.get("textarea").setValue("changed draft")
        await w.setProps({awaiting: true, status: "Waiting for transcript"})
        expect(w.get("textarea").attributes("disabled")).toBeDefined()
        expect(w.get('[aria-label="Send message"]').attributes("disabled")).toBeDefined()
        await w.get('[aria-label="Send message"]').trigger("click")
        expect(w.emitted("send")).toBeUndefined()
        expect(w.emitted("update:draft")?.[0]).toEqual(["changed draft"])
        await w.setProps({awaiting: false, draft: "", status: "Delivered"})
        expect((w.get("textarea").element as HTMLTextAreaElement).value).toBe("")
    })
    it("retains text on refusal and explains unavailable chat", async () => {
        const w = mount(AgentComposer, {props: {available: true}})
        await w.get("textarea").setValue("keep me")
        await w.setProps({error: "No pane"})
        expect((w.get("textarea").element as HTMLTextAreaElement).value).toBe("keep me")
        expect(w.text()).toContain("No pane")
        await w.setProps({available: false, reason: "Not permitted"})
        expect(w.get("textarea").attributes("disabled")).toBeDefined()
        expect(w.get('[role="status"]').text()).toBe("No pane")
    })
})
